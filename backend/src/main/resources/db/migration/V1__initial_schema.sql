CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255)             NOT NULL,
    display_name  VARCHAR(100)             NOT NULL,
    password_hash VARCHAR(255)             NOT NULL,
    role          VARCHAR(20)              NOT NULL,
    active        BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE boards (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120)             NOT NULL,
    description VARCHAR(2000),
    background  VARCHAR(40)              NOT NULL,
    owner_id    BIGINT                   NOT NULL REFERENCES users (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE board_members (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id  BIGINT                   NOT NULL REFERENCES boards (id) ON DELETE CASCADE,
    user_id   BIGINT                   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role      VARCHAR(20)              NOT NULL,
    starred   BOOLEAN                  NOT NULL DEFAULT FALSE,
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_board_members_board_user UNIQUE (board_id, user_id)
);

CREATE INDEX idx_board_members_user ON board_members (user_id);

CREATE TABLE board_lists (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id   BIGINT                   NOT NULL REFERENCES boards (id) ON DELETE CASCADE,
    name       VARCHAR(120)             NOT NULL,
    position   INTEGER                  NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_board_lists_board ON board_lists (board_id, position);

CREATE TABLE labels (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id BIGINT      NOT NULL REFERENCES boards (id) ON DELETE CASCADE,
    name     VARCHAR(60) NOT NULL,
    color    VARCHAR(20) NOT NULL
);

CREATE INDEX idx_labels_board ON labels (board_id);

CREATE TABLE cards (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id       BIGINT                   NOT NULL REFERENCES board_lists (id) ON DELETE CASCADE,
    title         VARCHAR(255)             NOT NULL,
    description   VARCHAR(10000),
    position      INTEGER                  NOT NULL,
    priority      VARCHAR(20)              NOT NULL,
    due_date      DATE,
    completed     BOOLEAN                  NOT NULL DEFAULT FALSE,
    assignee_id   BIGINT                   REFERENCES users (id) ON DELETE SET NULL,
    created_by_id BIGINT                   NOT NULL REFERENCES users (id),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_cards_list ON cards (list_id, position);
CREATE INDEX idx_cards_assignee ON cards (assignee_id);

CREATE TABLE card_labels (
    card_id  BIGINT NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    label_id BIGINT NOT NULL REFERENCES labels (id) ON DELETE CASCADE,
    PRIMARY KEY (card_id, label_id)
);

CREATE TABLE checklist_items (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id  BIGINT       NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    content  VARCHAR(500) NOT NULL,
    done     BOOLEAN      NOT NULL DEFAULT FALSE,
    position INTEGER      NOT NULL
);

CREATE INDEX idx_checklist_items_card ON checklist_items (card_id, position);

CREATE TABLE comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id    BIGINT                   NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    author_id  BIGINT                   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    body       VARCHAR(5000)            NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_comments_card ON comments (card_id, created_at);
